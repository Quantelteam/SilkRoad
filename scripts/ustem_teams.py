"""Builds supabase/seed_teams.sql from the public team catalog on USTEM Connect.

    python scripts/ustem_teams.py                 # fetch https://connect.ustem.kz/teams
    python scripts/ustem_teams.py teams.html      # or parse a saved copy

Takes only what the bot needs: program (FTC, or FLL for every FLL division),
team number, team name and city. Teams without a number are skipped; they can
still ask to be added through the bot, and a moderator decides.
"""

import html
import re
import sys
import urllib.request
from pathlib import Path

URL = "https://connect.ustem.kz/teams"
OUT = Path(__file__).resolve().parent.parent / "supabase" / "seed_teams.sql"


def _text(fragment: str) -> str:
    fragment = re.sub(r"<!--.*?-->|<[^>]+>", "", fragment)
    return re.sub(r"\s+", " ", html.unescape(fragment)).strip()


def _city(place: str) -> str:
    # "Астана қ." -> "Астана" ("қ." is the Kazakh abbreviation for city).
    return re.sub(r"\s+қ\.$", "", place).strip()


def parse(page: str) -> list[dict]:
    body = page[: page.find("self.__next_f")]
    teams = []
    for inner in re.findall(r'<a[^>]+href="/teams/[a-z0-9-]+"[^>]*>(.*?)</a>', body, flags=re.S):
        label = re.search(r"<span[^>]*>(.*?)</span>", inner, re.S)
        program = _text(label.group(1)) if label else ""
        if program == "FTC":
            program = "FTC"
        elif program.startswith("FLL"):
            program = "FLL"
        else:
            continue
        m = re.search(r'num mr-1\.5">(\d+)</span>(.*?)</span></h3>', inner, re.S)
        if not m:
            continue
        place = re.search(r'<p class="text-sm text-ink-2">(.*?)</p>', inner, re.S)
        city = _city(_text(place.group(1)).split(" · ")[0]) if place else ""
        teams.append({
            "program": program,
            "number": int(m.group(1)),
            "name": _text(m.group(2))[:60] or f"Team {m.group(1)}",
            "city": city[:40] or "Unknown",
        })
    # One row per (program, number); the catalog can list a team twice.
    unique = {(t["program"], t["number"]): t for t in teams}
    return sorted(unique.values(), key=lambda t: (t["program"], t["number"]))


def to_sql(teams: list[dict]) -> str:
    q = lambda s: "'" + s.replace("'", "''") + "'"
    rows = ",\n".join(
        f"  ({q(t['program'])}, {t['number']}, {q(t['name'])}, {q(t['city'])}, true, 'ustem')" for t in teams
    )
    return (
        "-- Generated by scripts/ustem_teams.py from https://connect.ustem.kz/teams. Do not edit by hand.\n"
        f"-- {len(teams)} FTC and FLL teams. Re-running keeps names and cities a team already has\n"
        "-- and only marks it as verified and on the USTEM list.\n"
        "insert into teams (program, number, name, city, verified, source) values\n"
        f"{rows}\n"
        "on conflict (program, number) do update set verified = true, source = 'ustem';\n"
    )


def main() -> None:
    if len(sys.argv) > 1:
        page = Path(sys.argv[1]).read_text(encoding="utf-8")
    else:
        req = urllib.request.Request(URL, headers={"User-Agent": "SilkRoadExchange-team-sync"})
        with urllib.request.urlopen(req, timeout=60) as res:
            page = res.read().decode("utf-8")
    teams = parse(page)
    OUT.write_text(to_sql(teams), encoding="utf-8")
    print(f"Wrote {len(teams)} teams to {OUT}")


if __name__ == "__main__":
    main()
