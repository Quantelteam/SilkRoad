"""Builds supabase/seed_parts_fll.sql from the FLL (LEGO) parts in site/data/parts-catalog.json.

    python scripts/fll_parts_sql.py

The bot and the website then use the same names for LEGO parts, so the site can
match a bot listing to its catalog entry (photo, part number, counts).
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "site" / "data" / "parts-catalog.json"
OUT = ROOT / "supabase" / "seed_parts_fll.sql"

# Site category ids -> the category labels the bot shows.
BOT_CATEGORY = {
    "sets": "Sets", "control": "Hubs", "motors": "Motors", "sensors": "Sensors",
    "batteries": "Power", "cables": "Cables", "other": "Other",
}


def main() -> None:
    parts = [p for p in json.loads(CATALOG.read_text(encoding="utf-8"))["parts"] if p.get("program") == "FLL"]
    if not parts:
        raise SystemExit("No FLL parts in the catalog")
    q = lambda s: "null" if s is None else "'" + str(s).replace("'", "''") + "'"
    rows = ",\n".join(
        f"  ({q(p['name'])}, {q(p['brand'])}, {q(p.get('sku'))}, {q(BOT_CATEGORY.get(p['category'], 'Other'))}, 'FLL')"
        for p in parts
    )
    OUT.write_text(
        "-- Generated by scripts/fll_parts_sql.py from site/data/parts-catalog.json. Do not edit by hand.\n"
        f"-- {len(parts)} LEGO Education SPIKE parts for FLL teams. Safe to re-run.\n"
        "insert into parts (name, brand, sku, category, program) values\n"
        f"{rows}\n"
        "on conflict (name, coalesce(brand, '')) do update set\n"
        "  sku = excluded.sku, category = excluded.category, program = excluded.program;\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(parts)} FLL parts to {OUT}")


if __name__ == "__main__":
    main()
